def board_of(mark, ent, boards):
    """按商标/企业判定子品牌板块。先商标（子品牌更具体）后企业名。"""
    for key, name in boards:
        if key and key in mark:
            return name
    for key, name in boards:
        if key and key in ent:
            return name
    return mark or ent or '其他'


def attr_group(mark, ent):
    """(group_key, jv_excluded, hit_reason)。归属判定：关键词命中 → 关键词排除 → 实体排除。

    返回 (None, False, '') 表示 12 家之外（未归属）。jv_excluded=True 表示命中集团但属合资，
    master 侧留行打标、不进 12 家统计。
    """
    for key, (cn, grp, kws, excl, _foot) in GROUPS.items():
        if not any(w in mark or w in ent for w in kws):
            continue
        if any(x in mark or x in ent for x in excl):
            return key, True, f'关键词排除:{cn}'
        if any(x in ent for x in EXCL_ENT.get(key, [])):
            return key, True, f'合资实体:{cn}'
        return key, False, ''
    return None, False, ''
